// netlify/functions/learn-access.mjs
//
// POST { email, next? }  ->  { ok: true }   (always, so nobody can use
//                                           it to find out who has
//                                           done a course)
//
// Emails a one-tap login link for BirdBox Learn. One login covers
// everything: online courses, and the coach's Trainer Directory listing
// (/learn/directory/). So anyone can ask for a link — an in-person
// graduate, or a coach from before our records began, needs to get in
// even with no online course, and they then see the courses they could
// buy. Accounts are only ever made here, when the person asks: nobody is
// emailed because an account was set up for them.
//
// Someone BirdBox knows (Nathan, 1 Nov 2026: bought from BirdBox, given
// programming, staff, or a listing the office made or approved) gets the
// whole of BirdBox Learn. Anyone else, mostly coaches whose course was
// before our records began, gets a directory-only login: the link opens
// their Trainer Directory listing, which stays hidden until the office
// has checked their course, and BirdBox Learn shows them nothing else.
// Courses only ever open with a purchase, so nothing can be copied; a
// spam sign-up only makes a hidden listing for the review queue. The
// reply is the same either way, so it never shows who has bought.
//
//   1. at most three links an hour per address, so the form cannot be
//      used to flood someone's inbox
//   2. known to BirdBox (knownToBirdBox), or the directory-only link
//   3. a login account is made for the email if it has none (confirmed)
//   4. a login link is generated by Supabase and sent from the BirdBox
//      domain through Resend (Supabase's own emails are not set up for
//      this project)
import { createClient } from "@supabase/supabase-js";
import { knownToBirdBox } from "../lib/known.mjs";

const db = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});

const OFFICE = "info@birdboxcoaching.com";
const FROM = process.env.ALERT_FROM || "alerts@send.birdboxcoaching.com";

const ok = () => new Response(JSON.stringify({ ok: true }), {
  status: 200, headers: { "Content-Type": "application/json", "Cache-Control": "no-store" },
});

export default async (req) => {
  if (req.method !== "POST") return new Response("Method not allowed", { status: 405 });

  let body = {};
  try { body = await req.json(); } catch (e) { return ok(); }
  // From the CoachRx move email (Nathan, 1 Nov 2026): their own code
  // stands for their email, so they need not type it, and the link goes
  // to the address on their offer whoever taps it.
  let email = String(body.email || "").trim().toLowerCase();
  if (typeof body.move === "string" && /^[0-9a-f]{64}$/.test(body.move)) {
    const { data: mo } = await db.schema("train").from("move_offers")
      .select("email").eq("code", body.move).maybeSingle();
    if (!mo) return ok();
    email = mo.email;
    // opens on their programming offer, not My courses (Nathan, 7 Nov 2026)
    body.next = "/learn/?move_offer=1";
  }
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email) || email.length > 254) return ok();

  // Only ever send people back into /learn/ on this site.
  const origin = new URL(req.url).origin;
  const next = typeof body.next === "string" && /^\/learn\/[\w\-./?=&%]*$/.test(body.next) ? body.next : "/learn/";

  try {
    const since = new Date(Date.now() - 3600 * 1000).toISOString();
    const { count } = await db.from("directory_link_sends")
      .select("id", { count: "exact", head: true }).eq("email", email).gte("sent_at", since);
    if ((count || 0) >= 3) return ok();
    await db.from("directory_link_sends").insert({ email });

    // From the welcome back email's box (?offer=back, Nathan, 7 Nov 2026):
    // a past member with an offer gets their login link; any other email
    // gets a note saying we have no offer under it, never the Trainer
    // Directory link, which only confused people.
    if (body.offer === "back") {
      const { data: cb } = await db.schema("train").from("comeback_offers")
        .select("first_name,status").eq("email", email).maybeSingle();
      if (!cb || !["emailed", "joined"].includes(cb.status)) { await sendNoOffer(email, origin); return ok(); }
    }

    const known = await knownToBirdBox(email);

    const { error: cErr } = await db.auth.admin.createUser({ email, email_confirm: true });
    if (cErr && !/already|registered|exists/i.test(cErr.message || "")) {
      console.error("learn-access createUser:", cErr.message);
    }

    const { data, error } = await db.auth.admin.generateLink({
      type: "magiclink",
      email,
      options: { redirectTo: origin + (known ? next : "/learn/directory/") },
    });
    if (error || !data?.properties?.action_link) {
      console.error("learn-access generateLink:", error?.message);
      return ok();
    }
    await sendLink(email, data.properties.action_link, origin, known, await firstName(email));
  } catch (err) {
    console.error("learn-access:", err && (err.message || err));
  }
  return ok();
};

// Their first name for the greeting, where we have it (Nathan, 7 Nov
// 2026): their CoachRx move offer, then their app record; else "there".
async function firstName(email) {
  const train = db.schema("train");
  const { data: mo } = await train.from("move_offers").select("first_name").eq("email", email).maybeSingle();
  if (mo?.first_name) return mo.first_name;
  const { data: cb } = await train.from("comeback_offers").select("first_name").eq("email", email).maybeSingle();
  if (cb?.first_name) return cb.first_name;
  const { data: a } = await train.from("athletes").select("first_name").ilike("email", email).limit(1);
  return a?.[0]?.first_name || null;
}

async function sendLink(to, link, origin, known = true, name = null) {
  const key = process.env.RESEND_API_KEY;
  if (!key) { console.warn("No Resend key; login link not sent to", to); return; }
  const hi = `Hi ${String(name || "").trim() || "there"},`;
  const hiHtml = hi.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

  // directory-only: say what the link is for
  const intro = known ? "Here is your BirdBox login link" :
    "Here is your link to the BirdBox Trainer Directory. Add the BirdBox course you did and we will check it; your listing goes live once we have";
  const text =
`${hi}

${intro}:

${link}

Tap it and you go straight in, logged in. The link works once and expires in 1 hour. If it has run out, ask for a new one at ${origin}/learn/

${known ? 'Once you are in, a box at the top asks you for a password, so next time you can log in with your email and password without waiting for a link.\n\n' : ""}Did not ask for this? You can ignore this email.

BirdBox Coaching
${origin}/learn/`;

  // Laid out as the move and welcome emails (Nathan, 7 Nov 2026): a white
  // card, one large dark button, and the password step said plainly.
  const p = "margin:0 0 14px;font-size:15px;line-height:1.6;color:#3d3936;";
  const html = `<!doctype html>
<html><body style="margin:0;padding:0;background:#f4f3f1;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" bgcolor="#f4f3f1" style="background:#f4f3f1;padding:32px 16px;"><tr><td align="center">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" bgcolor="#ffffff" style="max-width:520px;background:#ffffff;border-radius:14px;overflow:hidden;border:1px solid #e6e3e0;">
  <tr><td bgcolor="#191513" style="background:#191513;padding:16px 26px;font-size:12px;letter-spacing:3px;text-transform:uppercase;color:#ffffff;">BirdBox Coaching</td></tr>
  <tr><td style="padding:26px 26px 30px;">
    <h1 style="margin:0 0 16px;font-size:22px;color:#191513;letter-spacing:-0.3px;">Your login link</h1>
    <p style="${p}">${hiHtml}</p>
    <p style="${p}">${intro}. Tap the button and you are logged straight in.</p>
    <table role="presentation" cellpadding="0" cellspacing="0" style="margin:8px 0 18px;"><tr>
      <td bgcolor="#191513" style="background:#191513;border-radius:10px;"><a href="${link.replace(/&/g, "&amp;")}" style="display:inline-block;padding:15px 34px;color:#ffffff;font-size:17px;font-weight:700;text-decoration:none;">Log in</a></td></tr></table>
    ${known ? `<p style="${p}"><b>Then set a password.</b> Once you are in, a box at the top asks you for one, so next time you can log in with your email and password without waiting for a link.</p>` : ""}
    <p style="${p}">The link works once and runs out after 1 hour. If it has, ask for a new one at <a href="${origin}/learn/" style="color:#191513;">${origin.replace(/^https?:\/\//, "")}/learn</a>.</p>
    <p style="margin:0 0 14px;font-size:14px;line-height:1.6;color:#3d3936;">Did not ask for this? You can ignore this email.</p>
    <p style="margin:0;font-size:15px;line-height:1.6;color:#191513;">BirdBox Coaching</p>
  </td></tr>
</table></td></tr></table></body></html>`;

  try {
    const res = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: "Bearer " + key, "Content-Type": "application/json" },
      body: JSON.stringify({
        from: `BirdBox Coaching <${FROM}>`,
        to: [to],
        reply_to: OFFICE,
        subject: "Your BirdBox login link",
        text,
        html,
      }),
    });
    if (!res.ok) console.error("Resend rejected the login link to", to, await res.text());
  } catch (err) {
    console.error("Could not send the login link to", to, err.message);
  }
}

