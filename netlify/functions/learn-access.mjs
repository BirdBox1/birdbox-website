// netlify/functions/learn-access.mjs
//
// POST { email, next? }  ->  { ok: true }   (always, so nobody can use
//                                           it to find out who has
//                                           done a course)
//
// Emails a one-tap login link for BirdBox Learn. One login covers
// everything: online courses, and the coach's Trainer Directory listing
// (/learn/directory/). So anyone can ask for a link — an in-person
// graduate, or a coach from before our records began, needs to get in
// even with no online course, and they then see the courses they could
// buy. Accounts are only ever made here, when the person asks: nobody is
// emailed because an account was set up for them.
//
// Only for people BirdBox knows (Nathan, 1 Nov 2026): someone who has
// bought from BirdBox, been given programming, works for BirdBox, or has a
// directory listing the office set up. Anyone else gets the same reply and
// no email, so there are no spam accounts and nobody gets at the courses
// without paying, and the reply never shows who has bought.
//
//   1. at most three links an hour per address, so the form cannot be
//      used to flood someone's inbox
//   2. the email must belong to someone BirdBox knows (knownToBirdBox)
//   3. a login account is made for the email if it has none (confirmed)
//   4. a login link is generated by Supabase and sent from the BirdBox
//      domain through Resend (Supabase's own emails are not set up for
//      this project)
import { createClient } from "@supabase/supabase-js";
import Stripe from "stripe";

const db = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});

const OFFICE = "info@birdboxcoaching.com";
const FROM = process.env.ALERT_FROM || "alerts@send.birdboxcoaching.com";

const ok = () => new Response(JSON.stringify({ ok: true }), {
  status: 200, headers: { "Content-Type": "application/json", "Cache-Control": "no-store" },
});

export default async (req) => {
  if (req.method !== "POST") return new Response("Method not allowed", { status: 405 });

  let body = {};
  try { body = await req.json(); } catch (e) { return ok(); }
  const email = String(body.email || "").trim().toLowerCase();
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email) || email.length > 254) return ok();

  // Only ever send people back into /learn/ on this site.
  const origin = new URL(req.url).origin;
  const next = typeof body.next === "string" && /^\/learn\/[\w\-./?=&%]*$/.test(body.next) ? body.next : "/learn/";

  try {
    const since = new Date(Date.now() - 3600 * 1000).toISOString();
    const { count } = await db.from("directory_link_sends")
      .select("id", { count: "exact", head: true }).eq("email", email).gte("sent_at", since);
    if ((count || 0) >= 3) return ok();
    await db.from("directory_link_sends").insert({ email });

    if (!(await knownToBirdBox(email))) return ok();

    const { error: cErr } = await db.auth.admin.createUser({ email, email_confirm: true });
    if (cErr && !/already|registered|exists/i.test(cErr.message || "")) {
      console.error("learn-access createUser:", cErr.message);
    }

    const { data, error } = await db.auth.admin.generateLink({
      type: "magiclink",
      email,
      options: { redirectTo: origin + next },
    });
    if (error || !data?.properties?.action_link) {
      console.error("learn-access generateLink:", error?.message);
      return ok();
    }
    await sendLink(email, data.properties.action_link, origin);
  } catch (err) {
    console.error("learn-access:", err && (err.message || err));
  }
  return ok();
};

// Has this email bought from BirdBox, been given programming, or a staff
// or office-made listing? Any one is enough.
async function knownToBirdBox(email) {
  const like = email.replace(/[%_\\]/g, "\\$&");
  const has = async (q) => { const { count } = await q; return (count || 0) > 0; };
  const head = { count: "exact", head: true };
  const checks = [
    () => has(db.from("staff").select("id", head).ilike("email", like)),
    () => has(db.from("registrations").select("id", head).ilike("email", like)),
    () => has(db.from("learn_enrolments").select("course_id", head).ilike("email", like)),
    () => has(db.from("directory_profiles").select("id", head).ilike("email", like).neq("source", "self")),
    async () => {
      const train = db.schema("train");
      const { data: a } = await train.from("athletes").select("id").ilike("email", like).limit(5);
      const ids = (a || []).map((x) => x.id);
      if (!ids.length) return false;
      return (await has(train.from("enrolments").select("id", head).in("athlete_id", ids)))
          || (await has(train.from("purchases").select("id", head).in("athlete_id", ids)));
    },
    // anything paid on BirdBox's Stripe account: T-shirts, gift cards too
    async () => {
      if (!process.env.STRIPE_SECRET_KEY) return false;
      const stripe = new Stripe(process.env.STRIPE_SECRET_KEY);
      const found = await stripe.customers.search({ query: `email:'${email.replace(/'/g, "\\'")}'`, limit: 10 });
      for (const c of found.data || []) {
        const ch = await stripe.charges.list({ customer: c.id, limit: 10 });
        if ((ch.data || []).some((x) => x.paid && x.status === "succeeded")) return true;
      }
      return false;
    },
  ];
  for (const check of checks) {
    try { if (await check()) return true; } catch (e) { console.error("learn-access check:", e.message); }
  }
  return false;
}

async function sendLink(to, link, origin) {
  const key = process.env.RESEND_API_KEY;
  if (!key) { console.warn("No Resend key; login link not sent to", to); return; }

  const text =
`Hi,

Here is your BirdBox login link:

${link}

Tap it and you go straight in, logged in. The link works once and expires in 1 hour. If it has run out, ask for a new one at ${origin}/learn/

Once you are in, you can set a password under "Set or change your password" so you can log in without waiting for an email next time.

Did not ask for this? You can ignore this email.

BirdBox Coaching
${origin}/learn/`;

  const html = `<div style="font-family:-apple-system,Helvetica,Arial,sans-serif;font-size:16px;line-height:1.6;color:#16181b;max-width:520px">
<p>Hi,</p>
<p>Here is your BirdBox login link.</p>
<p style="margin:28px 0"><a href="${link.replace(/&/g, "&amp;")}" style="display:inline-block;background:#4FA8DE;color:#0C1116;text-decoration:none;font-weight:800;letter-spacing:.08em;text-transform:uppercase;font-size:14px;padding:14px 26px">Log in</a></p>
<p>The link works once and expires in 1 hour. If it has run out, ask for a new one at <a href="${origin}/learn/">${origin.replace(/^https?:\/\//, "")}/learn</a>.</p>
<p>Once you are in, you can set a password so you can log in without waiting for an email next time.</p>
<p style="color:#6c7178;font-size:14px">Did not ask for this? You can ignore this email.</p>
<p>BirdBox Coaching</p>
</div>`;

  try {
    const res = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: "Bearer " + key, "Content-Type": "application/json" },
      body: JSON.stringify({
        from: `BirdBox Coaching <${FROM}>`,
        to: [to],
        reply_to: OFFICE,
        subject: "Your BirdBox login link",
        text,
        html,
      }),
    });
    if (!res.ok) console.error("Resend rejected the login link to", to, await res.text());
  } catch (err) {
    console.error("Could not send the login link to", to, err.message);
  }
}
